# 给定列表 a = [5, 10, 15]，从键盘输入列表 b（输入格式用逗号分隔，如 2,4,6），计算 a 和 b 对应元素乘积的累加和，并输出结果。
# 示例：
# 输入：2,4,6
# 计算：5*2 + 10*4 + 15*6 = 10 + 40 + 90 = 140
# 输出：140
a=[5,10,15]
b=list(map(int,input("请输入三个元素，用逗号隔开").split(',')))
res=0
for i in range(len(a)):
    res=res+a[i]*b[i]
print(res)

