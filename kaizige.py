# a 和 b 是两个列表变量，列表 a 为 [3, 6, 9] 已给定，键盘输入列表 b，计算 a 中元素与 b 中对应元素乘积的累加和。
# 例如：键盘输入列表 b 为 [1,2, 3]，累加和为 13+26+3*9=42，因此，屏幕输出计算结果为 42
a=[3,6,9]
b=list(map(int,input("请输入三个元素").split(',')))
result =0
for i in range(len(a)):
    result+=a[i]*b[i]
print(result)
