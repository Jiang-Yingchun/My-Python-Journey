# turtle库的turtle.right()函数和turtle.fd()函数绘制一个平行四边形，边长为150 像素，内角为2 个 45 度和 2 个 135 度，效果如图所示。
import turtle #turtle就是乌龟的意思，就是让画笔她像乌龟一样去爬
turtle.fd(150)
turtle.right(45)
turtle.fd(150)
turtle.right(135)
turtle.fd(150)
turtle.right(45)
turtle.fd(150)
turtle.right(135)
turtle.done()






